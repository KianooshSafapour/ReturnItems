import { toEnDigits } from "./money";

/** نرمال‌سازی ارقام: فارسی/عربی → لاتین و حذف نویسه‌های غیررقمی */
export function digitsOnly(input: string): string {
  return toEnDigits(input).replace(/[^\d]/g, "");
}

/** شماره موبایل ایران معتبر است؟ 09xxxxxxxxx */
export function isValidIranMobile(phone: string): boolean {
  return /^09\d{9}$/.test(digitsOnly(phone));
}

/** الگوریتم Luhn برای شماره کارت ۱۶ رقمی */
export function isValidCardNumber(card: string): boolean {
  const digits = digitsOnly(card);
  if (!/^\d{16}$/.test(digits)) return false;
  let sum = 0;
  let alt = false;
  for (let i = digits.length - 1; i >= 0; i--) {
    let d = parseInt(digits[i], 10);
    if (alt) {
      d *= 2;
      if (d > 9) d -= 9;
    }
    sum += d;
    alt = !alt;
  }
  return sum % 10 === 0;
}


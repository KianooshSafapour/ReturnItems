/** تشخیص نام بانک از شماره کارت */
export function detectBankName(card: string): string | null {
  const d = digitsOnly(card);
  if (d.length < 6) return null;
  const prefix = d.slice(0, 6);
  const name = BANK_PREFIXES[prefix];
  return name && !name.includes("؟") ? name : null;
}

